def raw(start=0, boot=1, count=25):
    return dict(schema_version=1, device_id='TEST-NODE', boot_id=boot,
                seq_start=start, sample_rate_hz=25,
                samples=[[i * 40, int(90000 + 2000 * np.sin(i / 4)),
                          int(100000 + 2000 * np.sin(i / 4))]
                         for i in range(start, start + count)])


def test_parser_contains_failures_and_recovers_with_next_valid_packet():
    oversized = packet()
    oversized['uptime_s'] = 10 ** 400
    for line in (json.dumps(oversized), '{"x":' + '[' * 1100 + '0' + ']' * 1100 + '}',
                 '{"x":"' + 'a' * 17000 + '"}'):
        assert bridge.parse_packet(line) is None
    assert bridge.parse_packet(json.dumps(packet())) is not None


def test_old_samples_are_masked_without_losing_emergency_flags():
    p = verified_packet()
    p['uptime_s'] = 1000
    p['alerts']['sos'] = True
    parsed = bridge.parse_packet(json.dumps(p))
    assert parsed['alerts']['sos'] is True
    assert parsed['vitals']['heart_rate'] is None
    assert parsed['vitals']['heart_rate_status'] == 'stale'
    assert parsed['vitals']['tmp117_sensor_temperature_raw'] is None
    assert parsed['vitals']['wrist_skin_temperature_status'] == 'stale'
    assert parsed['vitals']['fever_screening']['input']['measured'] is False


def test_age_checks_accept_subsecond_remainder_and_uint32_wrap():
    p = packet()
    p['vitals']['heart_rate_timestamp_ms'] = 5999
    assert bridge.parse_packet(json.dumps(p))['vitals']['heart_rate'] == 72
    p['vitals']['heart_rate_timestamp_ms'] = 6000
    assert bridge.parse_packet(json.dumps(p))['vitals']['heart_rate'] is None
    p['uptime_s'] = 1
    p['vitals']['heart_rate_timestamp_ms'] = 0xffffffff - 100
    assert bridge.parse_packet(json.dumps(p))['vitals']['heart_rate'] == 72


def test_raw_validation_sequence_boot_and_timing_discontinuities():
    assert parse_raw_packet('[PPG] ' + json.dumps(raw())) is not None
    bad = raw()
    bad['samples'][0][1] = True
    assert parse_raw_packet('[PPG] ' + json.dumps(bad)) is None
    collector = WindowCollector()
    for seq in range(0, 250, 25):
        ready = collector.append(raw(seq))
    assert ready and len(collector.samples) == 250
    assert not collector.append(raw(300))  # Missing a batch.
    assert len(collector.samples) == 25
    assert not collector.append(raw(325, boot=2))
    assert len(collector.samples) == 25
    discontinuous = raw(350, boot=2)
    discontinuous['samples'][0][0] += 100
    assert not collector.append(discontinuous)
    assert collector.gaps >= 2


def test_features_have_training_inference_polarity_parity_and_no_nan():
    wave = np.sin(np.arange(250) / 4) + 100
    np.testing.assert_allclose(extract_features(wave), extract_features(-wave))
    assert np.isfinite(extract_features(np.zeros(250))).all()


def test_group_split_keeps_all_sessions_of_person_together():
    groups = np.repeat([f'P{i}' for i in range(10)], 4)
    labels = np.tile([0, 1, 0, 1], 10)
    splits = split_participants(labels, groups)
    identities = [set(groups[rows]) for rows in splits.values()]
    assert not identities[0] & identities[1]
    assert not identities[0] & identities[2]
    assert not identities[1] & identities[2]


def test_recording_keeps_unfiltered_samples_and_expires_stale_views(tmp_path):
    path = tmp_path / 'capture.jsonl'
    service = OpticalQualityService(recording_path=path, participant='P01', session='test')
    try:
        for seq in range(0, 250, 25):
            service.submit(raw(seq))
        service.queue.join()
        view = service.snapshot()
        assert view['status'] == 'model_missing'
        assert view['samples_collected'] == 250
        records = [json.loads(line) for line in path.read_text().splitlines()]
        assert len(records) == 10 and records[0]['participant'] == 'P01'
        service.last_received = time.monotonic() - 6
        assert service.snapshot()['waveform'] == []
    finally:
        service.close()
    with pytest.raises(FileExistsError):
        OpticalQualityService(recording_path=path, participant='P02', session='different')


def test_trained_artifact_runs_without_altering_other_fields():
    model = Path('models/ppg_quality.joblib')
    if not model.exists():
        pytest.skip('Public model is generated by the documented training command.')
    service = OpticalQualityService(model)
    try:
        for seq in range(0, 250, 25):
            service.submit(raw(seq))
        service.queue.join()
        result = service.snapshot()
        assert result['status'] == 'prediction'
        assert result['mode'] == 'shadow'
        assert 0 <= result['score'] <= 1
        assert result['domain'] == service.model['domain']
    finally:
        service.close()


def test_local_preparation_requires_review_and_excludes_uncertain_windows(tmp_path):
    recordings = tmp_path / 'recordings'
    recordings.mkdir()
    rows = [dict(participant='P01', session='test', packet=raw(seq))
            for seq in range(0, 500, 25)]
    (recordings / 'session.jsonl').write_text('\n'.join(json.dumps(row) for row in rows) + '\n')
    output = tmp_path / 'review'
    windows = prepare(recordings, output)
    assert len(windows) == 2
    assert not (output / 'training.npz').exists()  # No inferred labels.
    assert (output / 'review.html').exists()
    labels = output / 'labels.csv'
    labels.write_text(f'id,label\n{windows[0]["id"]},1\n{windows[1]["id"]},uncertain\n')
    prepare(recordings, output, labels)
    with np.load(output / 'training.npz', allow_pickle=False) as data:
        assert data['red'].shape == (1, 250)
        assert data['groups'].tolist() == ['P01']
        assert data['labels'].tolist() == [1]
