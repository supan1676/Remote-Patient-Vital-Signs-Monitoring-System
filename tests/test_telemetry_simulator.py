"""Synthetic demo must exercise real contracts and preserve missing-data meaning."""
import json
from pathlib import Path

import pytest

import telemetry_bridge as bridge
from alert_priority import AlertPriorityService
from care_workflow import CareWorkflow
from personal_baseline import PersonalBaseline
from ppg_quality import OpticalQualityService, parse_raw_packet
from telemetry_simulator import DEVICE_ID, PHASES, TelemetrySimulator, make_packet, scenario
from telemetry_store import TelemetryStore


def test_simulation_packets_validate_and_missing_data_is_not_a_normal_value():
    elapsed = 0
    for name, duration, _, _, usable, sos in PHASES:
        p = bridge.parse_packet(json.dumps(make_packet(100 + elapsed, elapsed)))
        assert p is not None, name
        assert p['device_id'] == DEVICE_ID
        assert p['alerts']['sos'] == sos
        assert (p['vitals']['heart_rate'] is not None) == usable
        assert p['vitals']['wrist_skin_temperature_c'] is None
        assert p['vitals']['estimated_core_temperature_c'] is None
        assert 'SIMULATED' in p['status_summary']
        elapsed += duration
    assert scenario(elapsed) == PHASES[0]


def test_waveform_batches_are_continuous_and_use_the_raw_parser():
    sim = TelemetrySimulator(None)
    first = sim.waveform(0, 0)
    second = sim.waveform(1, 0)
    assert parse_raw_packet('[PPG] ' + json.dumps(first)) == first
    assert second['seq_start'] == 25
    assert first['samples'][-1][0] + 40 == second['samples'][0][0]
    assert len(second['samples']) == 25


def test_simulation_drives_actual_priority_models_and_emergency_workflow(monkeypatch):
    if not all(Path(p).exists() for p in ('models/ppg_quality.joblib', 'models/alert_priority.joblib')):
        pytest.skip('Trained models are generated by the documented training commands.')
    store = TelemetryStore(':memory:')
    baseline = PersonalBaseline(store)
    baseline.start(DEVICE_ID, 'Synthetic integration test')
    optical = OpticalQualityService('models/ppg_quality.joblib')
    priority = AlertPriorityService('models/alert_priority.joblib')
    care = CareWorkflow(store)
    for name, value in dict(telemetry_store=store, personal_baseline=baseline,
                            optical_service=optical, priority_service=priority,
                            care_workflow=care, hardware_status=bridge.hardware_status.copy(),
                            last_alerts={}, latest_telemetry=None,
                            last_packet_time=None, latest_comparisons={}).items():
        monkeypatch.setattr(bridge, name, value)
    sim = TelemetrySimulator(bridge)
    try:
        second = 100
        for elapsed, expected in [(0, 'green'), (45, 'yellow'), (95, 'red')]:
            for _ in range(60):
                sim.step(second, elapsed)
                second += 1
            result = bridge.snapshot()
            assert result['priority']['zone'] == expected
            assert result['priority']['source'] == 'trained_model'
            assert result['optical']['status'] == 'prediction'
            assert result['status']['simulation'] is True
        sim.step(second, 215)  # Missing pulse phase.
        assert bridge.snapshot()['priority']['zone'] == 'unknown'
        assert bridge.snapshot()['telemetry']['vitals']['heart_rate'] is None
        sim.step(second + 1, 230)  # SOS remains red with absent pulse data.
        assert bridge.snapshot()['priority']['zone'] == 'red'
        assert bridge.snapshot()['priority']['source'] == 'device_alert'
        assert care.summary(DEVICE_ID)['incidents'][0]['kind'] == 'sos'
    finally:
        optical.close()
        priority.close()
        store.db.close()
