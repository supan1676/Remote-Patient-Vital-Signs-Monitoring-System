def export_demo(dataset, model_path, output):
    artifact = joblib.load(model_path)
    manifest = json.loads((dataset / 'manifest.json').read_text())
    arrays = {name: np.load(dataset / f'{name}.npy', mmap_mode='r', allow_pickle=False)
              for name in ('signals', 'quality', 'features', 'labels', 'profiles', 'families', 'patterns', 'splits')}
    cases = []
    test = np.flatnonzero((arrays['splits'] == 2) & (arrays['labels'] >= 0))
    with threadpool_limits(limits=1):
        all_predictions = artifact['estimator'].predict(arrays['features'][test])
        selected = []
        for label in range(3):
            rows = test[(arrays['labels'][test] == label) & (all_predictions == label)]
            selected.extend(rows[:3])
        selected.extend(np.flatnonzero((arrays['splits'] == 2) & (arrays['labels'] == -1))[:1])
        selected.extend(test[all_predictions != arrays['labels'][test]][:2])
        for index in selected:
            label = int(arrays['labels'][index])
            if label >= 0:
                probability = artifact['estimator'].predict_proba(arrays['features'][index:index + 1])[0]
                prediction = int(np.argmax(probability))
                class_scores = dict(zip(LABELS, map(float, probability)))
            else:
                prediction, class_scores = -1, None
            actual = LABELS[label] if label >= 0 else 'unknown'
            predicted = LABELS[prediction] if prediction >= 0 else 'unknown'
            cases.append(dict(id=int(index), profile=int(arrays['profiles'][index]),
                description=f'{predicted.title()} output · {actual} policy label' +
                            (' · model error' if actual != predicted else ''),
                family=manifest['family_codes'][int(arrays['families'][index])],
                pattern=manifest['pattern_codes'][int(arrays['patterns'][index])],
                label=actual, prediction=predicted, scores=class_scores,
                signals=[[float(v) if np.isfinite(v) else None for v in row] for row in arrays['signals'][index]],
                quality=arrays['quality'][index].tolist()))
    payload = json.dumps(dict(version=artifact['model_version'], cases=cases), allow_nan=False).replace('<', '\\u003c')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(HTML.replace('__DATA__', payload))
    print(f'Exported {len(cases)} held-out examples to {output}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dataset', type=Path, default=Path('data/synthetic-priority-v1'))
    parser.add_argument('--model', type=Path, default=Path('models/alert_priority.joblib'))
    parser.add_argument('--output', type=Path, default=Path('models/alert_priority.demo.html'))
    args = parser.parse_args()
    export_demo(args.dataset, args.model, args.output)


if __name__ == '__main__':
    main()
